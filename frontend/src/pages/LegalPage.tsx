function Section({ section }: { section: LegalSection }) {
  return (
    <section id={section.id} className="scroll-mt-24">
      <h2 className="text-base font-bold text-foreground sm:text-lg">{section.title}</h2>
      {section.paragraphs?.map((text, index) => (
        <p key={index} className="mt-3 text-sm leading-relaxed text-muted-foreground">
          {text}
        </p>
      ))}
      {section.bullets && section.bullets.length > 0 && (
        <ul className="mt-3 space-y-2">
          {section.bullets.map((text, index) => (
            <li key={index} className="flex gap-2 text-sm leading-relaxed text-muted-foreground">
              <span aria-hidden className="mt-[7px] h-1.5 w-1.5 shrink-0 rounded-full bg-primary/70" />
              <span>{text}</span>
            </li>
          ))}
        </ul>
      )}
    </section>
  );
}

