/**
 * Public legal surface — `/privacy` and `/terms`.
 *
 * Why this is a product dependency and not a formality:
 * Google refuses to publish an OAuth consent screen until the app has a
 * reachable home page, privacy policy and terms of service, and both pages
 * must be readable **without signing in** (Google's reviewers crawl them
 * anonymously). That is why these routes sit outside the auth gate in
 * `App.tsx` — a login wall here reads as a broken policy page and blocks
 * "Publish app", which in turn blocks every "Sign in with Google" user.
 *
 * The Google-specific wording in §4 and §5 of the privacy policy is not
 * decorative either: an app that uses Google user data must disclose its
 * Limited Use compliance and, for YouTube scopes, the YouTube API Services
 * Terms. Removing those paragraphs is a verification failure.
 */

