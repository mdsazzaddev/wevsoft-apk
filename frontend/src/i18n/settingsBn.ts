function resolveSettingsLang(code?: string | null): string {
  const raw = String(code || '').trim();
  if (!raw) return 'en';
  if (SETTINGS_LANG_MAPS[raw]) return raw;
  const lower = raw.toLowerCase();
  if (lower.startsWith('zh')) {
    if (lower.includes('tw') || lower.includes('hk') || lower.includes('hant')) return 'zh-TW';
    return 'zh-CN';
  }
  const base = lower.split(/[-_]/)[0];
  return base;
}

/** Merge Bangla base dictionary with generated extras. */
const SETTINGS_BN_MERGED: Record<string, string> = { ...SETTINGS_BN, ...SETTINGS_BN_EXTRA };

/**
 * Translate settings UI copy. Keys are the English source strings (safe with dots/colons).
 * Looks up the active UI language map; missing entries fall back to English.
 */
export function useSettingsTr() {
  const { i18n } = useTranslation();
  const lang = resolveSettingsLang(i18n?.language);
  return useCallback((s?: string | null) => {
    const v = String(s ?? '');
    if (!v) return v;
    if (lang === 'bn' || lang.startsWith('bn')) return SETTINGS_BN_MERGED[v] ?? v;
    const map = SETTINGS_LANG_MAPS[lang];
    return map?.[v] ?? v;
  }, [lang]);
}

/** Lowercased haystack of English + current-language label for settings search. */
export function settingsSearchBlob(english: string | null | undefined, tr: (s: string) => string): string {
  const en = String(english ?? '');
  const localized = tr(en);
  return `${en} ${localized}`.toLowerCase();
}
