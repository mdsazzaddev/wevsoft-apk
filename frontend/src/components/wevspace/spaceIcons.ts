/** Falls back to a neutral globe so an unknown name never breaks a render. */
export function spaceIcon(name: unknown): LucideIcon {
  return ICONS[String(name || '')] || Globe;
}

/** Icon for a link row, resolved through the shared platform table. */
export function spaceLinkIcon(platform: unknown): LucideIcon {
  const def = SPACE_LINK_PLATFORMS.find((p) => p.id === platform);
  return spaceIcon(def?.icon || 'Link');
}
